// Writes music/playlist.js for DirtyDave FM from the audio files in music/ (subfolders too).
// Usage: put tracks into music/, then run: node tools/playlist.mjs
import { readdirSync, writeFileSync, mkdirSync } from 'node:fs';
import { join, relative, extname } from 'node:path';
import { fileURLToPath } from 'node:url';
const dir = fileURLToPath(new URL('../music/', import.meta.url));
mkdirSync(dir, { recursive: true });
const AUDIO = new Set(['.mp3', '.m4a', '.aac', '.ogg', '.oga', '.opus', '.wav', '.flac', '.webm']);
const walk = d => readdirSync(d, { withFileTypes: true }).flatMap(e => e.isDirectory() ? walk(join(d, e.name)) : AUDIO.has(extname(e.name).toLowerCase()) ? [relative(dir, join(d, e.name)).split('\\').join('/')] : []);
const list = walk(dir).sort();
writeFileSync(join(dir, 'playlist.js'), '// Generated by tools/playlist.mjs - run it again after adding or removing tracks\nwindow.PLAYLIST = ' + JSON.stringify(list, null, 1) + ';\n');
console.log(`DirtyDave FM: ${list.length} track(s) in music/`);
